#!/usr/bin/env node
// FONT-AXIS-SURVEY — which families do the Claude-Design references ask for with a NON-WEIGHT
// variable axis, and does the face we bundle actually carry it?
//
// WHY THIS EXISTS. gen-pack-fonts.js reached for `<pkg>-latin-wght-normal.woff2` for every
// variable family — the weight-axis slice, with every other axis frozen at its default. For a
// family with an OPTICAL SIZE axis that silently substitutes a different typeface: the reference
// asks Google for `Fraunces:opsz,wght@9..144,500`, so `font-optical-sizing: auto` (the CSS
// default) drives opsz to the display size and draws the high-contrast Didone cut, while our
// slice stayed frozen at opsz 14 — the sturdy text cut, which at 120px reads as a heavy slab and
// was reported as "wrong display serif family on every frame".
//
//   node scripts/font-axis-survey.js           # report what the references ask for
//   node scripts/font-axis-survey.js --check   # FAIL if a bundled face ignores an asked-for axis
//
// --check is a real functional probe, not a source lint: it renders a word in headless Chrome at
// two extremes of the axis and fails when the advance does not move, which is exactly what a
// frozen-axis slice looks like from the outside.

const fs = require("node:fs");
const path = require("node:path");
const { FONT_FACES } = require("../src/fonts/pack_fonts.js");

const SRC = path.join(__dirname, "..", "..", "templete-design", "keyframe-handoff", "source");
// Google's axis name -> the two values to probe. A face that carries the axis renders these at
// visibly different widths; a frozen slice renders them identically.
const PROBE = { opsz: [9, 144], wdth: [75, 125], slnt: [0, -10], GRAD: [-200, 150] };

function findChromium() {
  if (process.env.PUPPETEER_EXECUTABLE_PATH) return process.env.PUPPETEER_EXECUTABLE_PATH;
  const home = process.env.USERPROFILE || process.env.HOME || "";
  const root = path.join(home, ".cache", "puppeteer", "chrome");
  const out = [];
  try {
    for (const dir of fs.readdirSync(root)) {
      for (const sub of ["chrome-win64/chrome.exe", "chrome-linux64/chrome",
        "chrome-mac-x64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing"]) {
        const exe = path.join(root, dir, sub);
        if (fs.existsSync(exe)) out.push(exe);
      }
    }
  } catch { /* no cache */ }
  return out.sort().reverse()[0] || null;
}

function survey() {
  const want = new Map();
  const weights = new Map();
  for (const f of fs.readdirSync(SRC)) {
    if (!f.endsWith(".dc.html")) continue;
    const t = fs.readFileSync(path.join(SRC, f), "utf8");
    for (const r of t.match(/family=[A-Za-z0-9+%-]+(?::[a-zA-Z,]+@[0-9.,;]+)?/g) || []) {
      const m = /^family=([^:&]+)(?::([a-zA-Z,]+)@([0-9.,;]+))?/.exec(r);
      if (!m) continue;
      const fam = decodeURIComponent(m[1].replace(/\+/g, " "));
      const axes = (m[2] || "wght").split(",");
      if (!want.has(fam)) want.set(fam, new Set());
      for (const a of axes) if (a !== "ital") want.get(fam).add(a);
      // WHICH WEIGHTS THE DESIGN ACTUALLY ASKED FOR. Google serves only what the URL requests, so
      // a family requested as `wght@500;600` was never available to the reference at 400 — the
      // design cannot be rendering lighter than its lightest request. We default display type to
      // the CSS default of 400, which for those families is a visibly lighter colour on the page.
      const wi = axes.indexOf("wght");
      if (m[3] && wi >= 0) {
        if (!weights.has(fam)) weights.set(fam, new Set());
        for (const tup of m[3].split(";")) {
          const v = Number(tup.split(",")[wi]);
          if (Number.isFinite(v) && v >= 1 && v <= 1000) weights.get(fam).add(v);
        }
      }
    }
  }
  return [...want.entries()].map(([fam, ax]) => {
    const ws = [...(weights.get(fam) || [])].sort((a, b) => a - b);
    return { fam, axes: [...ax].sort(), bundled: !!FONT_FACES[fam], weights: ws, minWeight: ws[0] || null };
  }).sort((a, b) => a.fam.localeCompare(b.fam));
}

// Emit the floor table the engine reads: only families the references never requested below 400,
// because those are the ones our CSS default renders too light. Committed like font_metrics.js.
function writeWeights(rows) {
  const floors = {};
  for (const r of rows) if (r.bundled && r.minWeight && r.minWeight > 400) floors[r.fam] = r.minWeight;
  const body = Object.keys(floors).sort().map((k) => `  ${JSON.stringify(k)}: ${floors[k]},`).join(String.fromCharCode(10));
  const out = `// AUTO-GENERATED by scripts/font-axis-survey.js — committed on purpose. DO NOT hand-edit.
//
// THE LIGHTEST WEIGHT EACH DESIGN ACTUALLY ASKED GOOGLE FOR, for the families whose answer is above
// the CSS default of 400. Google serves only the weights the request names, so a reference that
// asked for \`Fraunces:opsz,wght@9..144,500;9..144,600\` could not have rendered a single glyph at
// 400 — while our display type, which declares no weight, renders at exactly that. Measured on the
// chrome lockup (identical string, identical size, same polarity) the reference carries ~17% more
// ink than our render of it.
//
// This is a FLOOR, not a setting: a skin that declares its own displayWeight always wins, and a
// family absent from this table is left at the browser default, which is what its design used.
//
// Regenerate: node scripts/font-axis-survey.js

const WEIGHT_FLOOR = {
${body}
};

// The weight display type should render at for this family, or null to leave it to the browser.
function weightFloor(family) {
  if (!family) return null;
  const key = Object.keys(WEIGHT_FLOOR).find((k) => k.toLowerCase() === String(family).toLowerCase().trim());
  return key ? WEIGHT_FLOOR[key] : null;
}

module.exports = { WEIGHT_FLOOR, weightFloor };
`;
  fs.writeFileSync(path.join(__dirname, "..", "src", "fonts", "font_weights.js"), out);
  console.log(`[font-weights] wrote src/fonts/font_weights.js — ${Object.keys(floors).length} family(ies) with a floor above 400`);
}

async function check(rows) {
  const targets = rows.filter((r) => r.bundled && r.axes.some((a) => a !== "wght"));
  if (!targets.length) { console.log("no bundled family is asked for with a non-weight axis"); return 0; }
  const puppeteer = require("puppeteer-core");
  const exe = findChromium();
  if (!exe) { console.error("no cached Chrome — set PUPPETEER_EXECUTABLE_PATH"); return 3; }
  const browser = await puppeteer.launch({ executablePath: exe, headless: true, args: ["--no-sandbox", "--font-render-hinting=none"] });
  let failed = 0;
  try {
    const page = await browser.newPage();
    await page.setContent(`<!DOCTYPE html><meta charset="utf-8"><style>${targets.map((t) => FONT_FACES[t.fam]).join("")}</style><body></body>`, { waitUntil: "load" });
    await page.evaluate(() => document.fonts.ready);
    for (const t of targets) {
      for (const axis of t.axes) {
        if (axis === "wght" || !PROBE[axis]) continue;
        const [lo, hi] = PROBE[axis];
        const w = await page.evaluate(async (fam, ax, a, b) => {
          await document.fonts.load(`200px '${fam}'`);
          const mk = (css) => {
            const s = document.createElement("span");
            s.style.cssText = `font-family:'${fam}';position:absolute;white-space:nowrap;${css}`;
            s.textContent = "Handgloves";
            document.body.appendChild(s);
            const r = s.getBoundingClientRect().width;
            s.remove();
            return r;
          };
          // 1. the axis is CARRIED by the bundled bytes at all…
          const explicit = [mk(`font-size:200px;font-variation-settings:'${ax}' ${a}`),
            mk(`font-size:200px;font-variation-settings:'${ax}' ${b}`)];
          // 2. …and, for optical size, that it is actually DRIVEN by the font size, which is the
          //    only reason our compositions get the display cut — they never set the axis by hand.
          const auto = ax !== "opsz" ? null
            : [mk("font-size:14px") / 14, mk("font-size:200px") / 200];
          return { explicit, auto };
        }, t.fam, axis, lo, hi);
        const moved = Math.abs(w.explicit[0] - w.explicit[1]) / Math.max(1, w.explicit[0]);
        // A frozen slice renders both ends identically; a face whose opsz is present but not
        // driven by font-size would pass the explicit probe and still ship the wrong cut.
        const autoMoved = w.auto ? Math.abs(w.auto[0] - w.auto[1]) / Math.max(0.001, w.auto[0]) : 1;
        const ok = moved > 0.01 && autoMoved > 0.01;
        if (!ok) failed++;
        console.log(`  ${ok ? "ok  " : "FAIL"}  ${t.fam.padEnd(24)} ${axis} ${lo}->${hi}  advance ${w.explicit[0].toFixed(1)} -> ${w.explicit[1].toFixed(1)} (${(moved * 100).toFixed(1)}%)`
          + (w.auto ? `  ·  size-driven 14px->200px em-advance ${w.auto[0].toFixed(3)} -> ${w.auto[1].toFixed(3)} (${(autoMoved * 100).toFixed(1)}%)` : ""));
        if (!ok) console.log(`        the bundled slice ignores '${axis}' — gen-pack-fonts.js needs { axis: "${axis}" } for ${t.fam}`);
      }
    }
  } finally { await browser.close().catch(() => {}); }
  console.log(`\n${targets.length} family(ies) checked, ${failed} failed`);
  return failed ? 1 : 0;
}

(async () => {
  const rows = survey();
  const multi = rows.filter((r) => r.axes.some((a) => a !== "wght"));
  console.log(`families requested: ${rows.length} | with non-wght axes: ${multi.length}`);
  for (const r of multi) console.log(` ${r.bundled ? "BUNDLED" : "absent "}  ${r.fam.padEnd(26)} ${r.axes.join(",")}`);
  fs.writeFileSync(path.join(__dirname, "..", "framecheck", "font-axis-survey.json"), JSON.stringify(rows, null, 1));
  if (!process.argv.includes("--check")) writeWeights(rows);
  if (process.argv.includes("--check")) process.exit(await check(rows));
})();
